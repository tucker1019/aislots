CREATE TABLE IF NOT EXISTS lobby_admin_configs (
 section TEXT PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
 published_version BIGINT NOT NULL DEFAULT 1 CHECK (published_version > 0),
 draft_version BIGINT NOT NULL DEFAULT 0 CHECK (draft_version >= 0),
 published JSONB NOT NULL,
 draft JSONB,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS lobby_admin_config_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 section TEXT NOT NULL REFERENCES lobby_admin_configs(section),
 version BIGINT NOT NULL,
 status TEXT NOT NULL CHECK (status IN ('draft','published','superseded')),
 document JSONB NOT NULL,
 username TEXT NOT NULL,
 reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE (section,version)
);
CREATE TABLE IF NOT EXISTS lobby_admin_config_releases (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 section TEXT NOT NULL REFERENCES lobby_admin_configs(section),
 version BIGINT NOT NULL,
 request_id TEXT NOT NULL,
 fingerprint TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(section,request_id)
);
CREATE TABLE IF NOT EXISTS lobby_admin_runtime_state (
 instance TEXT PRIMARY KEY,
 revision BIGINT NOT NULL DEFAULT 0,
 last_error TEXT NOT NULL DEFAULT '',
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
