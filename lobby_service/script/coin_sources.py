"""Single source registry. Values are persistent IDs: never recycle or rename them."""
from pathlib import Path
import subprocess

# English enum identifier, stable stored value, description.
SOURCES = [
    ('SourceInviteReward', 'act_007', '邀请好友奖励加币'),
    ('SourceGameBet', 'game_001', '游戏投注扣币'),
    ('SourceGameWin', 'game_002', '游戏逐轮派彩'),
    ('SourceNewbieRecharge', 'act_006', '新手累计充值奖励'),
    ('SourceVIPUpgrade', 'vip_001', 'VIP升级礼金'),
    ('SourceVIPWeekly', 'vip_002', 'VIP周工资'),
    ('SourceVIPMonthly', 'vip_003', 'VIP月工资'),
    ('SourceRebateDaily', 'act_002', '日反水奖励加币'),
    ('SourceRebateWeekly', 'act_003', '周反水奖励加币'),
    ('SourceRebateMonthly', 'act_004', '月反水奖励加币'),
    ('SourceLoserReturn', 'act_005', '亏损返还奖励加币'),
    ('SourceCheckinReward', 'act_001', '签到奖励加币'),
    ('SourceRechargeCredit', 'rch_001', '充值本金加币'),
    ('SourceRechargeBonus', 'rch_002', '充值赠送加币'),
    ('SourceRechargeFee', 'rch_003', '充值手续费减币'),
]

def main():
    names, values = set(), set()
    for name, value, _ in SOURCES:
        if name in names or value in values:
            raise ValueError('duplicate source name or value')
        names.add(name)
        values.add(value)
    root = Path(__file__).resolve().parent.parent
    code = '// Code generated by script/coin_sources.py. DO NOT EDIT.\npackage coinsource\n\ntype Source string\n\nconst (\n'
    for name, value, description in SOURCES:
        code += f'\t{name} Source = "{value}" // {description}\n'
    code += ')\n'
    target = root / 'pkg/coinsource/source_gen.go'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(code)
    subprocess.run(['gofmt', '-w', str(target)], check=True)
    doc = '# 金币 source 注册表\n\n由 `script/coin_sources.py` 生成。新增类型只修改脚本中的 SOURCES，执行 `make source`。已有值永久保留，不能修改或复用。\n\n| 英文枚举 | 流水存储值 | 含义 |\n| --- | --- | --- |\n'
    for name, value, description in SOURCES:
        doc += f'| `{name}` | `{value}` | {description} |\n'
    (root / 'docs/coin-sources.md').write_text(doc)

if __name__ == '__main__':
    main()
