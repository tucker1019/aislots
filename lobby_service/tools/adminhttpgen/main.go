// adminhttpgen emits only the admin router; player descriptors and routes are untouched.
package main

import (
	"fmt"
	"go/format"
	annotations "google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
	"os"
	"strings"
)

func main() {
	b, e := os.ReadFile("protos/admin_descriptor.pb")
	if e != nil {
		panic(e)
	}
	var set descriptorpb.FileDescriptorSet
	if e = proto.Unmarshal(b, &set); e != nil {
		panic(e)
	}
	s := `// Code generated by tools/adminhttpgen. DO NOT EDIT.
package adminapi
import("net/http";"apps/app/apis/lobby/api/internal/adminauth")
func(a *API) Register(m *http.ServeMux,auth *adminauth.Auth){
`
	for _, f := range set.File {
		if f.GetPackage() != "apis.lobby.admin.v1" {
			continue
		}
		for _, service := range f.Service {
			for _, method := range service.Method {
				rule, ok := proto.GetExtension(method.Options, annotations.E_Http).(*annotations.HttpRule)
				if !ok {
					continue
				}
				name := method.GetName()
				permission := ""
				handler := ""
				switch name {
				case "Overview":
					permission = "overview.read"
					handler = "overview"
				case "Members":
					permission = "members.read"
					handler = "members"
				case "Member":
					permission = "members.read"
					handler = "member"
				case "Orders":
					permission = "orders.read"
					handler = "orders"
				case "Review":
					permission = "orders.review"
					handler = "review"
				case "Audit":
					permission = "audit.read"
					handler = "audit"
				default:
					continue
				}
				verb, path := "GET", rule.GetGet()
				if rule.GetPost() != "" {
					verb, path = "POST", rule.GetPost()
				}
				s += fmt.Sprintf("m.HandleFunc(%q,auth.Protect(%q,a.%s))\n", verb+" "+path, permission, handler)
			}
		}
	}
	s += "}\n"
	out, e := format.Source([]byte(strings.TrimSpace(s)))
	if e != nil {
		panic(e)
	}
	if e = os.WriteFile("app/apis/lobby/api/internal/adminapi/routes.gen.go", out, 0644); e != nil {
		panic(e)
	}
	generateConfig(&set)

}

func generateConfig(set *descriptorpb.FileDescriptorSet) {
	source := `// Code generated by tools/adminhttpgen. DO NOT EDIT.
package adminconfig
import("net/http";"gorm.io/gorm")
func Register(mux *http.ServeMux,db *gorm.DB,protect func(string,http.HandlerFunc)http.HandlerFunc,actor func(*http.Request)string){s:=service{db,actor}
`
	routes := map[string][2]string{"List": {"configs.read", "list"}, "Detail": {"configs.read", "get"}, "Draft": {"configs.write", "draft"}, "Validate": {"configs.write", "validate"}, "Publish": {"configs.publish", "publish"}, "Rollback": {"configs.publish", "rollback"}}
	for _, file := range set.File {
		if file.GetPackage() != "apis.lobby.admin.config.v1" {
			continue
		}
		for _, service := range file.Service {
			for _, method := range service.Method {
				route, ok := routes[method.GetName()]
				if !ok {
					panic("unknown admin config method")
				}
				rule, ok := proto.GetExtension(method.Options, annotations.E_Http).(*annotations.HttpRule)
				if !ok {
					panic("HTTP annotation required")
				}
				verb, path := "GET", rule.GetGet()
				if rule.GetPost() != "" {
					verb, path = "POST", rule.GetPost()
				}
				source += fmt.Sprintf("mux.HandleFunc(%q,protect(%q,s.%s))\n", verb+" "+path, route[0], route[1])
			}
		}
	}
	source += "}\n"
	out, e := format.Source([]byte(source))
	if e != nil {
		panic(e)
	}
	if e = os.WriteFile("app/apis/lobby/api/internal/adminconfig/routes.gen.go", out, 0644); e != nil {
		panic(e)
	}
}
